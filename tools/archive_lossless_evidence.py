"""Shared immutable evidence store; generated cleanup follows full readback."""
from pathlib import Path
import gzip
import hashlib
import json
import subprocess


def sha(raw):return hashlib.sha256(raw).hexdigest()


def freeze(root,out,paths,metadata,cleanup_roots,cleanup=False):
    root=root.resolve();out=out.resolve();assert out.is_relative_to(root/'analysis') and not out.exists()
    cleanup_roots=[p.resolve() for p in cleanup_roots]
    assert cleanup_roots and all(p.is_relative_to(root/'validation') for p in cleanup_roots)
    files={};compressed={};candidates=[]
    for path in sorted(set(paths)):
        path=path.resolve();assert path.is_relative_to(root)
        raw=path.read_bytes();name=path.relative_to(root).as_posix();digest=sha(raw)
        if path.is_relative_to(root/'validation') or len(raw)>65536:
            stored='objects/'+digest+'.gz';dest=out/stored;dest.parent.mkdir(parents=True,exist_ok=True)
            if not dest.exists():dest.write_bytes(gzip.compress(raw,mtime=0))
            encoded=dest.read_bytes();assert gzip.decompress(encoded)==raw
            compressed[name]=dict(stored=stored,raw_sha256=digest,raw_bytes=len(raw),stored_sha256=sha(encoded))
        else:
            dest=out/name;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(raw);files[name]=digest
        if any(path.is_relative_to(p) for p in cleanup_roots) and (
            path.suffix in ['.bin','.out','.o','.s','.d','.dll'] or path.name.endswith(('-events.json','-clock.json')) or
            path.name in ['expected.h','psg.h']):candidates.append(path)
    manifest=dict(metadata,files=files,compressed=compressed,removed_verified_generated=[])
    target=out/'manifest.json';target.write_text(json.dumps(manifest,indent=2)+'\n')
    for name,digest in files.items():assert sha((out/name).read_bytes())==digest
    for item in compressed.values():
        encoded=(out/item['stored']).read_bytes();assert sha(encoded)==item['stored_sha256']
        raw=gzip.decompress(encoded);assert sha(raw)==item['raw_sha256'] and len(raw)==item['raw_bytes']
    if cleanup:
        tracked=set(subprocess.check_output(['git','ls-files','-z'],cwd=root).decode('utf-8').split('\0'))
        assert all(p.relative_to(root).as_posix() not in tracked for p in candidates)
        for path in candidates:
            resolved=path.resolve();assert any(resolved.is_relative_to(p) for p in cleanup_roots)
            name=resolved.relative_to(root).as_posix();assert name not in tracked
            item=compressed[name];raw=resolved.read_bytes();assert sha(raw)==item['raw_sha256']
            assert gzip.decompress((out/item['stored']).read_bytes())==raw
            manifest['removed_verified_generated'].append(dict(path=name,bytes=len(raw)));resolved.unlink()
        target.write_text(json.dumps(manifest,indent=2)+'\n')
    size=sum(p.stat().st_size for p in out.rglob('*') if p.is_file())
    removed=sum(x['bytes'] for x in manifest['removed_verified_generated'])
    print(len(compressed),'compressed references;',removed,'generated bytes removed;',removed-size,'net bytes freed')
    return manifest


def resume_verified_cleanup(root,out,cleanup_roots):
    """Resume an interrupted cleanup using its fully written evidence manifest."""
    root=root.resolve();out=out.resolve();roots=[p.resolve() for p in cleanup_roots]
    assert out.is_relative_to(root/'analysis') and roots and all(p.is_relative_to(root/'validation') for p in roots)
    target=out/'manifest.json';m=json.loads(target.read_bytes())
    assert not m['removed_verified_generated'],'Archive cleanup already finalized'
    tracked=set(subprocess.check_output(['git','ls-files','-z'],cwd=root).decode('utf-8').split('\0'))
    candidates=[]
    for name,digest in m['files'].items():
        p=(out/name).resolve();assert p.is_relative_to(out) and sha(p.read_bytes())==digest
    for name,item in m['compressed'].items():
        stored=(out/item['stored']).resolve();assert stored.is_relative_to(out)
        encoded=stored.read_bytes();assert sha(encoded)==item['stored_sha256']
        raw=gzip.decompress(encoded);assert sha(raw)==item['raw_sha256'] and len(raw)==item['raw_bytes']
        p=(root/name).resolve();assert p.is_relative_to(root)
        generated=(p.suffix in ['.bin','.out','.o','.s','.d','.dll'] or p.name.endswith(('-events.json','-clock.json')) or p.name in ['expected.h','psg.h'])
        if generated and any(p.is_relative_to(folder) for folder in roots):
            assert name not in tracked
            if p.exists():assert sha(p.read_bytes())==item['raw_sha256']
            candidates.append((name,p,item))
    # Every object and remaining capture is verified before any further deletion.
    for name,p,item in candidates:
        if p.exists():
            assert sha(p.read_bytes())==item['raw_sha256'];p.unlink()
        m['removed_verified_generated'].append(dict(path=name,bytes=item['raw_bytes']))
    m['cleanup_resumed_after_interruption']=True
    temp=target.with_suffix('.json.tmp');temp.write_text(json.dumps(m,indent=2)+'\n');temp.replace(target)
    print('Resumed verified cleanup:',len(candidates),'generated files')
    return m
