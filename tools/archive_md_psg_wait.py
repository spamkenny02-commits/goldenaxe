"""Freeze first physical FIFO wait/emission proof before verified cleanup."""
import gzip
import hashlib
import json
import subprocess
import sys
from actor_reference import ROOT


def sha(raw):return hashlib.sha256(raw).hexdigest()


def main():
    out=ROOT/'analysis/md-psg-wait-v0203';assert not out.exists(),'Immutable archive exists'
    folder=ROOT/'validation/md-psg-wait';report=json.loads((ROOT/'analysis/md_psg_wait_report.json').read_text())
    for name,h in report['sources'].items():assert sha((ROOT/'megadrive/src'/name).read_bytes())==h
    assert sha((folder/'out/release/rom.bin').read_bytes())==report['kernel_sha256']
    baseline=ROOT/'analysis/md-io-clock-v0203/manifest.json';old=json.loads(baseline.read_text())
    assert old['compressed']['emulator/genesis_plus_gx_io_libretro.dll']['raw_sha256']==report['observer_core_sha256']
    for result in report['results']:
        assert result['done'] and not result['failures'] and result['groups']==10260 and result['bytes']==23940 and result['plain_core_identical']
        raw=(folder/(result['region']+'-rows.json')).read_bytes();assert sha(raw)==result['rows_sha256']
        rows=json.loads(raw);assert len(rows)==10260
        assert {(r['kind'],r['phase']) for r in rows}=={(k,p) for k in range(3) for p in range(3420)}
        assert all(0<=r['errors_master'][0]<1000 and all(-14<=e<=7 for e in r['relative_errors_master']) for r in rows)
    oracle=ROOT/'analysis/loading-psg-v0203/validation/loading-psg-deadlines/inputs.json'
    assert sha(oracle.read_bytes())==report['fixture_sha256']
    assert sha((ROOT/'analysis/loading_psg_deadlines_report.json').read_bytes())==report['source_dates_sha256']
    playable=sha((ROOT/'gaw-megadrive.bin').read_bytes());assert playable=='7660a4b5949d0f3362c4795ed5eb238f86c289708b51d1dda6eec669b4d3ecb7'
    paths={ROOT/'README.md',ROOT/'analysis/md_psg_wait_milestone.md',ROOT/'analysis/md_psg_wait_report.json'}
    paths.update(ROOT/'megadrive/src'/name for name in report['sources'])
    paths.update(ROOT/'tools'/name for name in ['validate_md_psg_wait.py','archive_md_psg_wait.py'])
    paths.update(p for p in folder.rglob('*') if p.is_file())
    files={};compressed={};candidates=[]
    for p in sorted(paths):
        raw=p.read_bytes();h=sha(raw);name=p.relative_to(ROOT).as_posix()
        if p.is_relative_to(folder) or len(raw)>65536:
            blob='objects/'+h+'.gz';dest=out/blob;dest.parent.mkdir(parents=True,exist_ok=True)
            if not dest.exists():dest.write_bytes(gzip.compress(raw,mtime=0))
            assert gzip.decompress(dest.read_bytes())==raw
            compressed[name]=dict(stored=blob,raw_sha256=h,raw_bytes=len(raw),stored_sha256=sha(dest.read_bytes()))
            if p.is_relative_to(folder) and (p.suffix in ['.bin','.out','.o','.s','.d','.dll'] or p.name.endswith(('-rows.json','-events.json')) or p.name=='cases.h'):candidates.append(p)
        else:
            dest=out/name;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(raw);files[name]=h
    data=dict(playable_sha256=playable,production_reader_wired=False,baseline_manifest_sha256=sha(baseline.read_bytes()),
        observer_core_sha256=report['observer_core_sha256'],source_fixture_sha256=report['fixture_sha256'],files=files,compressed=compressed,removed_verified_generated=[])
    manifest=out/'manifest.json';manifest.write_text(json.dumps(data,indent=2)+'\n')
    if '--cleanup' in sys.argv:
        for p in candidates:
            target=p.resolve();assert target.is_relative_to(folder.resolve())
            name=target.relative_to(ROOT).as_posix();assert not subprocess.check_output(['git','ls-files','--',name],cwd=ROOT)
            item=compressed[name];raw=target.read_bytes();assert sha(raw)==item['raw_sha256'] and gzip.decompress((out/item['stored']).read_bytes())==raw
            data['removed_verified_generated'].append(dict(path=name,bytes=len(raw)));target.unlink()
        manifest.write_text(json.dumps(data,indent=2)+'\n')
    print(len(files),'snapshots;',len(compressed),'compressed references;',sum(v['bytes'] for v in data['removed_verified_generated']),'generated bytes removed')


if __name__=='__main__':main()
