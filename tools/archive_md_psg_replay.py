"""Freeze actual native loader->PSG replay proof,then verified generated cleanup."""
import gzip
import hashlib
import json
import subprocess
import sys
from actor_reference import ROOT


def sha(raw):return hashlib.sha256(raw).hexdigest()


def main():
    out=ROOT/'analysis/md-psg-replay-v0203';assert not out.exists(),'Immutable archive exists'
    folder=ROOT/'validation/md-psg-replay';report=json.loads((ROOT/'analysis/md_psg_replay_report.json').read_text())
    for name,h in report['helpers'].items():assert sha((ROOT/'megadrive/src'/(name+'.c')).read_bytes())==h
    for name,h in report['replay_sources'].items():assert sha((ROOT/'megadrive/src'/name).read_bytes())==h
    assert sha((folder/'out/release/rom.bin').read_bytes())==report['kernel_sha256']
    baseline=ROOT/'analysis/md-io-clock-v0203/manifest.json';old=json.loads(baseline.read_text())
    assert old['compressed']['emulator/genesis_plus_gx_io_libretro.dll']['raw_sha256']==report['observer_core_sha256']
    for result in report['results']:
        assert result['done'] and not result['failures'] and result['cases']==48 and result['extra_cases']==7 and result['bytes']==2976 and result['plain_core_identical']
        assert len(result['rows'])==48 and {(r['case'],r['wrapped']) for r in result['rows']}=={(i,bool(w)) for i in range(24) for w in range(2)}
        assert all(0<=e<3420 for row in result['rows'] for e in row['errors_master'])
        assert result['poll_gap_master'][1]<6840 and result['seed_gap_master'][1]<6840
        assert sha((folder/(result['region']+'-events.json')).read_bytes())==result['events_sha256']
        assert len(result['synthetic'])==7 and [r['bytes'] for r in result['synthetic']]==[4,8,8,0,0,0,0]
    fixture=ROOT/'analysis/loading-psg-v0203/validation/loading-psg-deadlines/inputs.json'
    assert sha(fixture.read_bytes())==report['fixture_sha256']
    assert sha((ROOT/'analysis/loading_psg_deadlines_report.json').read_bytes())==report['source_dates_sha256']
    playable=sha((ROOT/'gaw-megadrive.bin').read_bytes());assert playable=='7660a4b5949d0f3362c4795ed5eb238f86c289708b51d1dda6eec669b4d3ecb7'
    paths={ROOT/'README.md',ROOT/'analysis/md_psg_replay_milestone.md',ROOT/'analysis/md_psg_replay_report.json'}
    paths.update(p for p in (ROOT/'megadrive/src').iterdir() if p.suffix in ['.c','.h','.inc','.s'])
    paths.update(ROOT/'tools'/name for name in ['validate_md_psg_replay.py','archive_md_psg_replay.py','validate_queued_loading.py','validate_native_room_finish.py','validate_reader_timing.py'])
    paths.update(p for p in folder.rglob('*') if p.is_file())
    files={};compressed={};candidates=[]
    for p in sorted(paths):
        raw=p.read_bytes();h=sha(raw);name=p.relative_to(ROOT).as_posix()
        if p.is_relative_to(folder) or len(raw)>65536:
            blob='objects/'+h+'.gz';dest=out/blob;dest.parent.mkdir(parents=True,exist_ok=True)
            if not dest.exists():dest.write_bytes(gzip.compress(raw,mtime=0))
            assert gzip.decompress(dest.read_bytes())==raw
            compressed[name]=dict(stored=blob,raw_sha256=h,raw_bytes=len(raw),stored_sha256=sha(dest.read_bytes()))
            if p.is_relative_to(folder) and (p.suffix in ['.bin','.out','.o','.s','.d','.dll'] or p.name.endswith(('-clock.json','-events.json')) or p.name in ['expected.h','psg.h']):candidates.append(p)
        else:
            dest=out/name;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(raw);files[name]=h
    data=dict(playable_sha256=playable,production_async_consumer=False,producer_consumer_overlap=False,
        baseline_manifest_sha256=sha(baseline.read_bytes()),observer_core_sha256=report['observer_core_sha256'],source_fixture_sha256=report['fixture_sha256'],
        files=files,compressed=compressed,removed_verified_generated=[])
    manifest=out/'manifest.json';manifest.write_text(json.dumps(data,indent=2)+'\n')
    if '--cleanup' in sys.argv:
        for p in candidates:
            target=p.resolve();assert target.is_relative_to(folder.resolve())
            name=target.relative_to(ROOT).as_posix();assert not subprocess.check_output(['git','ls-files','--',name],cwd=ROOT)
            item=compressed[name];raw=target.read_bytes();assert sha(raw)==item['raw_sha256'] and gzip.decompress((out/item['stored']).read_bytes())==raw
            data['removed_verified_generated'].append(dict(path=name,bytes=len(raw)));target.unlink()
        manifest.write_text(json.dumps(data,indent=2)+'\n')
    print(len(files),'snapshots;',len(compressed),'compressed references;',sum(v['bytes'] for v in data['removed_verified_generated']),'generated bytes removed')


if __name__=='__main__':main()
