"""Generate the two-plane SMS-to-MD expansion lookup, independent of game assets."""
import hashlib,json
from actor_reference import ROOT

def generate():
 values=[]
 for word in range(65536):
  a,b=word>>8,word&255;value=0
  for bit in range(7,-1,-1):value=(value<<4)|((a>>bit)&1)|(((b>>bit)&1)<<1)
  values.append(value)
 text='/* Generated by tools/generate_pattern_pairs.py: high byte plane0,low byte plane1. */\nstatic const u32 pattern_pairs[65536]={\n'+'\n'.join(','.join('0x%08xUL'%v for v in values[n:n+8])+',' for n in range(0,len(values),8))+'\n};\n'
 target=ROOT/'megadrive/src/pattern_pair_lut.inc'
 if not target.exists() or target.read_text()!=text:target.write_text(text)
 report=dict(entries=65536,rom_bytes=262144,sha256=hashlib.sha256(target.read_bytes()).hexdigest(),asset_independent=True)
 (ROOT/'analysis/pattern_pairs_assets_report.json').write_text(json.dumps(report,indent=2)+'\n');print('Pattern pair table:65536 entries,256KiB ROM.')
if __name__=='__main__':generate()
