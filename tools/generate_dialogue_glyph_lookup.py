"""Invert the source charset, retaining the reverse search's last match."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def lookup():
    data = (ROOT / 'megadrive/src/menu_data.c').read_text()
    charset = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', data.split('const u8 dialog_charset[] = {', 1)[1].split('};', 1)[0]))
    assert len(charset) == 191
    assert charset in (ROOT / 'input/original.sms').read_bytes()
    table = [80] * 256
    for index, value in enumerate(charset):
        table[value] = index
    table[0xb0] = table[ord('-')]
    for value in range(256):
        normalized = ord('-') if value == 0xb0 else value
        expected = next((i for i in range(190, -1, -1) if charset[i] == normalized), 80)
        assert table[value] == expected
    return charset, table

def main():
    _, table = lookup()
    lines = ['/* Generated by tools/generate_dialogue_glyph_lookup.py from the SMS charset. */',
             'static const u8 dialogue_glyph_lookup[256] = {']
    for start in range(0, 256, 16):
        lines.append('    ' + ','.join(f'0x{x:02x}' for x in table[start:start+16]) + ',')
    lines.append('};')
    path = ROOT / 'megadrive/src/dialogue_glyph_lookup.inc'
    data = ('\r\n'.join(lines) + '\r\n').encode('ascii')
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)
    print('Dialogue charset: 256 exact reverse-search results generated.')

if __name__ == '__main__':
    main()
